BORD = Border(left=thin, right=thin, top=thin, bottom=thin)
WRAP = Alignment(horizontal="left", vertical="top", wrap_text=True)
CENT = Alignment(horizontal="center", vertical="center", wrap_text=True)

wb = openpyxl.Workbook()
WS = wb.active
WS.title = "Питч"
R = 1
NC = 4

def merged(text, font=None, fill=None):
    global R
    WS.merge_cells(start_row=R, start_column=1, end_row=R, end_column=NC)
    c = WS.cell(row=R, column=1, value=text)
    c.alignment = WRAP
    if font: c.font = font
    if fill:
        for i in range(1, NC + 1):
            WS.cell(row=R, column=i).fill = fill
    R += 1

def section(name):
    merged(name, S_FONT, S_FILL)

def bullets(items):
    for it in items:
        merged("· " + it)

def table(headers, rows):
    global R
    for i, h in enumerate(headers, 1):
        c = WS.cell(row=R, column=i, value=h)
        c.font = H_FONT; c.fill = H_FILL; c.alignment = CENT; c.border = BORD
    R += 1
    for row in rows:
        for i, v in enumerate(row, 1):
            c = WS.cell(row=R, column=i, value=v)
            c.alignment = WRAP; c.border = BORD
        R += 1
    R += 1

